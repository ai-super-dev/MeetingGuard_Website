"""
Writes the thin route files under src/app/(en) and src/app/(es)/es.

Every page exists in English (at the root) and Spanish (under /es/). Each
route file only picks the language and hands over to a view in src/views/,
where the page itself lives. Run from the project root after adding a page:

    python scripts/generate-routes.py
"""
import pathlib

APP = pathlib.Path(__file__).resolve().parent.parent / "src" / "app"

# (route folder, view module, view component, metadata function, extra props)
STATIC = [
    ("", "HomePage", "HomePage", "homeMetadata", ""),
    ("privacy-policy", "LegalDocPage", "LegalDocPage", "legalMetadata", 'doc="privacy"'),
    ("terms-of-service", "LegalDocPage", "LegalDocPage", "legalMetadata", 'doc="terms"'),
]

# (route folder, view module, component, metadata fn, params function source, slug type)
DYNAMIC = []

# The web agenda: its own layout (src/app/(app-en)/app, src/app/(app-es)/es/app).
# (route folder under /app, view component, metadata key)
AGENDA = [
    ("", "AgendaPage", "agenda"),
    ("tasks", "TasksPage", "tasks"),
    ("account", "AccountPage", "account"),
    ("sign-in", "SignInPage", "signIn"),
    ("invite", "InvitePage", "invite"),
]

HEADER = "// Generated by scripts/generate-routes.py. Edit the view in src/views/ instead.\n"


def static_file(lang, view, comp, meta, extra):
    meta_args = f'"{lang}"' + (f', "{extra.split("=")[1].strip(chr(34))}"' if extra else "")
    props = f'lang="{lang}"' + (f" {extra}" if extra else "")
    return (
        HEADER
        + f'import {{ {comp}, {meta} }} from "@/views/{view}";\n\n'
        + f"export const metadata = {meta}({meta_args});\n\n"
        + f"export default function Page() {{\n  return <{comp} {props} />;\n}}\n"
    )


def dynamic_file(lang, view, comp, meta, params, slug_type):
    imports = []
    if "FEATURE_SLUGS" in params:
        imports.append('import { FEATURE_SLUGS, type FeatureSlug } from "@/lib/routes";')
    if "USE_CASE_SLUGS" in params:
        imports.append('import { USE_CASE_SLUGS, type UseCaseSlug } from "@/lib/routes";')
    names = [comp, meta] + (["blogSlugs"] if "blogSlugs" in params else [])
    imports.append(f'import {{ {", ".join(names)} }} from "@/views/{view}";')
    cast = "" if slug_type == "string" else f" as {slug_type}"
    return (
        HEADER
        + "\n".join(imports)
        + "\n\ntype Props = { params: Promise<{ slug: string }> };\n\n"
        + "export const dynamicParams = false;\n\n"
        + f"export function generateStaticParams() {{\n  return {params};\n}}\n\n"
        + "export async function generateMetadata({ params }: Props) {\n"
        + "  const { slug } = await params;\n"
        + f'  return {meta}("{lang}", slug{cast});\n'
        + "}\n\n"
        + "export default async function Page({ params }: Props) {\n"
        + "  const { slug } = await params;\n"
        + f'  return <{comp} lang="{lang}" slug={{slug{cast}}} />;\n'
        + "}\n"
    )


def agenda_file(lang, comp, key):
    return (
        HEADER
        + f'import {{ {comp} }} from "@/views/agenda/{comp}";\n'
        + 'import { agendaMetadata } from "@/views/agenda/meta";\n\n'
        + f'export const metadata = agendaMetadata("{lang}", "{key}");\n\n'
        + f"export default function Page() {{\n  return <{comp} />;\n}}\n"
    )


def write_agenda(lang, folder, text):
    base = APP / "(app-en)" / "app" if lang == "en" else APP / "(app-es)" / "es" / "app"
    target = base / folder / "page.tsx" if folder else base / "page.tsx"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text, encoding="utf-8")


def write(lang, folder, text):
    base = APP / "(en)" if lang == "en" else APP / "(es)" / "es"
    target = base / folder / "page.tsx" if folder else base / "page.tsx"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text, encoding="utf-8")


def main(only=None):
    for lang in ("en", "es"):
        for folder, view, comp, meta, extra in STATIC:
            if only and view not in only:
                continue
            write(lang, folder, static_file(lang, view, comp, meta, extra))
        for folder, view, comp, meta, params, slug_type in DYNAMIC:
            if only and view not in only:
                continue
            write(lang, folder, dynamic_file(lang, view, comp, meta, params, slug_type))
        for folder, comp, key in AGENDA:
            if only and comp not in only:
                continue
            write_agenda(lang, folder, agenda_file(lang, comp, key))
    print("routes written")


if __name__ == "__main__":
    import sys

    main(set(sys.argv[1:]) or None)
